function parseDurationToMinutes(durationStr) {
  let minutes = 0;
  const hMatch = durationStr.match(/(\d+)h/);
  const mMatch = durationStr.match(/(\d+)m/);
  if (hMatch) minutes += parseInt(hMatch[1]) * 60;
  if (mMatch) minutes += parseInt(mMatch[1]);
  return minutes;
}

// External booking redirects. TravelMate remains the source of trip details.
function tmTripRoute(item) {
  const trip = window.TravelMateStore?.getActiveTrip?.() || {};
  const clean = value => String(value || "").trim();
  const invalid = value => !value || /^(undefined|null|-)$/i.test(value.trim());
  let from = clean(trip.origin);
  let to = clean(trip.destination);
  if (invalid(from)) from = "";
  if (invalid(to)) to = "";
  return { trip, from, to };
}

function tmOpenExternal(url) {
  if (!url) return false;
  // Open only a new tab. Never fall back to changing the TravelMate tab,
  // which caused two apparent redirects when the popup was blocked.
  const opened = window.open(url, "_blank", "noopener,noreferrer");
  if (!opened) {
    alert("Your browser blocked the new tab. Allow pop-ups for TravelMate and click again.");
    return false;
  }
  return true;
}

function tmDate(trip) {
  const date = String(trip?.startDate || "").slice(0, 10);
  return /^\d{4}-\d{2}-\d{2}$/.test(date) ? date : "";
}

function tmTravelerCount(trip) {
  const travelers = Number.parseInt(trip?.travelers, 10);
  return Number.isFinite(travelers) && travelers > 0 ? travelers : 1;
}

function tmSlug(value) {
  return String(value || "").toLowerCase().replace(/\([^)]*\)/g, " ").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function tmRedbusBusUrl(from, to, date) {
  const cityName = value => String(value || "")
    .split(",")[0]
    .replace(/\([^)]*\)/g, " ")
    .trim();
  const source = cityName(from);
  const destination = cityName(to);
  if (!source || !destination || /^(undefined|null|-)$/i.test(source) || /^(undefined|null|-)$/i.test(destination)) return "";

  const redbusCities = {
    bengaluru: { id: 122, name: "Bengaluru" },
    bangalore: { id: 122, name: "Bengaluru" },
    hyderabad: { id: 124, name: "Hyderabad" }
  };
  const sourceCity = redbusCities[tmNormalizeLocation(source)];
  const destinationCity = redbusCities[tmNormalizeLocation(destination)];
  if (!sourceCity || !destinationCity) return "";

  const params = new URLSearchParams({
    fromCityId: String(sourceCity.id),
    fromCityName: sourceCity.name,
    toCityId: String(destinationCity.id),
    toCityName: destinationCity.name,
    ref: "search"
  });
  if (/^\d{4}-\d{2}-\d{2}$/.test(date)) {
    const [, year, month, day] = date.match(/^(\d{4})-(\d{2})-(\d{2})$/);
    const monthName = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"][Number(month) - 1];
    if (monthName) {
      const redbusDate = `${day}-${monthName}-${year}`;
      params.set("onward", redbusDate);
      params.set("doj", redbusDate);
    }
  }
  const base = `https://www.redbus.in/bus-tickets/${tmSlug(sourceCity.name)}-to-${tmSlug(destinationCity.name)}`;
  return `${base}?${params.toString()}`;
}

