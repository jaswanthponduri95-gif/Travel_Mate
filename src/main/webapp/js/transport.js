function tmRailStationForCity(city) {
  const rows = Array.isArray(window.TM_RAILWAY_STATIONS) ? window.TM_RAILWAY_STATIONS : [];
  const normalized = tmNormalizeLocation(String(city || "").split(",")[0]);
  if (!normalized) return null;

  const mappedCode = RAILWAY_CITY_OVERRIDES[normalized] || STATION_CODE_MAP[normalized];
  if (mappedCode) {
    const mapped = rows.find(row => row[0] === mappedCode);
    if (mapped) return { code: mapped[0], name: mapped[1] };
  }

  const exact = rows.find(row => tmNormalizeLocation(row[1]) === normalized);
  return exact ? { code: exact[0], name: exact[1] } : null;
}

function getStationCode(city) {
  return tmRailStationForCity(city)?.code || "";
}

const AIRPORT_CITY_ALIASES = {
  bangalore: "bengaluru",
  bombay: "mumbai",
  calcutta: "kolkata",
  cochin: "kochi",
  madras: "chennai",
  mysore: "mysuru"
};

function tmAirportForCity(city) {
  const airports = Array.isArray(window.TM_INDIAN_AIRPORTS) ? window.TM_INDIAN_AIRPORTS : [];
  const normalized = tmNormalizeLocation(String(city || "").split(",")[0]);
  if (!normalized) return null;

  const byCode = airports.find(airport => airport[0].toLowerCase() === normalized);
  if (byCode) return { code: byCode[0], name: byCode[2] || byCode[1] };

  const searchName = AIRPORT_CITY_ALIASES[normalized] || normalized;
  const matches = airports.filter(airport =>
    tmNormalizeLocation(airport[2]) === searchName ||
    tmNormalizeLocation(airport[3]) === searchName
  );
  matches.sort((a, b) => {
    const sizeOrder = { large: 0, medium: 1, small: 2 };
    return (sizeOrder[a[5]] ?? 3) - (sizeOrder[b[5]] ?? 3) || a[0].localeCompare(b[0]);
  });
  return matches.length ? { code: matches[0][0], name: matches[0][2] || matches[0][1] } : null;
}

function renderTransportReference(item) {
  if (item.mode === "train") {
    const from = tmRailStationForCity(item.origin);
    const to = tmRailStationForCity(item.destination);
    return from && to
      ? `Stations: ${from.code} — ${from.name} → ${to.code} — ${to.name}`
      : "Railway station codes";
  }
  if (item.mode === "flight") {
    const from = tmAirportForCity(item.origin);
    const to = tmAirportForCity(item.destination);
    return from && to
      ? `Airports: ${from.code} — ${from.name} → ${to.code} — ${to.name}`
      : "Airport codes";
  }
  if (item.mode === "bus") return "Route search uses city names (no nationwide bus code)";
  return item.number || "";
}

function tmRedrailUrl(from, to, date) {
  const source = tmRailStationForCity(from);
  const destination = tmRailStationForCity(to);
  if (!source || !destination) return "";
  const params = new URLSearchParams({
    src: source.code,
    dst: destination.code,
    srcName: source.name,
    dstName: destination.name
  });
  if (date) params.set("date", date);
  return `https://www.redbus.in/railways/search?${params.toString()}`;
}

function tmBookingFlightsUrl(from, to, date, returnDate, travelers) {
  const source = tmAirportForCity(from);
  const destination = tmAirportForCity(to);
  if (!source || !destination) return "";
  const params = new URLSearchParams({
    type: returnDate ? "ROUNDTRIP" : "ONEWAY",
    adults: String(travelers),
    cabinClass: "ECONOMY",
    children: "",
    from: `${source.code}.AIRPORT`,
    to: `${destination.code}.AIRPORT`,
    fromName: source.name,
    toName: destination.name,
    fromCountry: "IN",
    toCountry: "IN"
  });
  if (date) params.set("depart", date);
  if (returnDate) params.set("return", returnDate);
  return `https://flights.booking.com/flights/${source.code}.AIRPORT-${destination.code}.AIRPORT/?${params.toString()}`;
}

function tmUberUrl(from, to) {
  const params = new URLSearchParams();
  params.set("action", "setPickup");
  params.set("pickup[formatted_address]", from);
  params.set("dropoff[formatted_address]", to);
  return `https://m.uber.com/ul/?${params.toString()}`;
}

function tmRapidoUrl(from, to) {
  // Rapido's public web entry does not provide a stable documented route-prefill URL.
  // Keep the route in a Google Maps directions link as a useful companion.
  const params = new URLSearchParams({ api: "1", origin: from, destination: to, travelmode: "driving" });
  return `https://www.google.com/maps/dir/?${params.toString()}`;
}

function tmSelfDriveMapUrl(trip, from, to) {
  const stops = [];
  (trip?.days || []).forEach(day => (day.stops || []).forEach(stop => {
    const lat = Number(stop.lat), lng = Number(stop.lng);
    if (Number.isFinite(lat) && Number.isFinite(lng)) stops.push(`${lat},${lng}`);
  }));
  const selectedHotel = String(trip?.accommodation?.name || "").trim();
  const mapDestination = selectedHotel
    ? `${selectedHotel}, ${to}`
    : to;
  const params = new URLSearchParams({ api: "1", origin: from, destination: mapDestination, travelmode: "driving" });
  if (stops.length) params.set("waypoints", stops.slice(0, 8).join("|"));
  return `https://www.google.com/maps/dir/?${params.toString()}`;
}

